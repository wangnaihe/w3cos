#!/usr/bin/env python3
"""Rank `w3cos leak-lint --json` findings over Code-OSS into a markdown report.

Score = severity (error 3, warning 2, info 0.5)
      + 1 if a `--fix` codemod applies
      + 1 for shared layers (vs/base, vs/platform, vs/editor/common), which live for the whole session
      + 0.5 for patterns that close a cycle by themselves (back pointers, mutual properties,
        listeners/bound functions that capture `this`).
"""
import argparse
import collections
import json

SEVERITY = {"error": 3.0, "warning": 2.0, "info": 0.5}
CORE = ("vs/base/", "vs/platform/", "vs/editor/common/")
CYCLE = {"back-pointer", "mutual-properties", "cross-file-cycle"}


def score(f):
    s = SEVERITY[f["severity"]]
    if f["fix"]:
        s += 1
    if f["file"].startswith(CORE):
        s += 1
    if f["pattern"] in CYCLE or "captures `this`" in f["message"] or "bind(this)" in f["message"]:
        s += 0.5
    return s


def area(path):
    parts = path.split("/")
    if len(parts) > 2 and parts[1] == "workbench" and parts[2] in ("contrib", "services", "api", "browser"):
        return "/".join(parts[:3])
    return "/".join(parts[:2])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("report")
    ap.add_argument("--commit", default="")
    ap.add_argument("--pin", default="")
    ap.add_argument("--top", type=int, default=40)
    args = ap.parse_args()
    data = json.load(open(args.report))
    findings = data["findings"]
    out = []
    w = out.append
    w("# Code-OSS leak-lint findings\n")
    w(f"Generated by `ports/vscode/scripts/vscode-patches.sh lint` (`w3cos leak-lint src --exclude /test/`).")
    w(f"Upstream pin `{args.pin}`; checkout HEAD `{args.commit}` (pin + patch queue).\n")
    s = data["summary"]
    w(f"{data['files_scanned']} files, {data['parse_failures']} parse failures, {data['ir_lowered']} lowered to W3IR. "
      f"{len(findings)} findings: {s['error']} error, {s['warning']} warning, {s['info']} info.\n")
    w("## By pattern\n")
    w("| pattern | findings | warning+ | auto-fixable |")
    w("| --- | ---: | ---: | ---: |")
    per = collections.defaultdict(lambda: [0, 0, 0])
    for f in findings:
        row = per[f["pattern"]]
        row[0] += 1
        row[1] += f["severity"] != "info"
        row[2] += f["fix"] is not None
    for pattern, (n, warn, fix) in sorted(per.items(), key=lambda kv: -kv[1][0]):
        w(f"| `{pattern}` | {n} | {warn} | {fix} |")
    w("\n## By area (warning+)\n")
    w("| area | findings |")
    w("| --- | ---: |")
    areas = collections.Counter(area(f["file"]) for f in findings if f["severity"] != "info")
    for name, n in areas.most_common(15):
        w(f"| `{name}` | {n} |")
    w(f"\n## Top {args.top} (ranked)\n")
    w("| # | score | location | pattern | fix | finding |")
    w("| ---: | ---: | --- | --- | --- | --- |")
    ranked = sorted(findings, key=lambda f: (-score(f), f["file"], f["line"]))
    for i, f in enumerate(ranked[: args.top], 1):
        msg = f["message"].replace("|", "\\|")
        w(f"| {i} | {score(f):.1f} | `{f['file']}:{f['line']}` | `{f['pattern']}` | {f['fix'] or ''} | {msg} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()

function getKeyMap() {
  const map = {};
  for (const code of Object.keys(US)) {
    const v = US[code] || ['', '', '', '', '', ''];
    map[code] = {
      value: v[0],
      withShift: v[1],
      withAltGr: v[2],
      withShiftAltGr: v[3],
      withLevel5: v[4],
      withLevel3Level5: v[5],
    };
  }
  return map;
}

function getCurrentKeyboardLayout() {
  return { model: 'pc105', group: 0, layout: 'us', variant: '', options: '', rules: 'evdev' };
}

function onDidChangeKeyboardLayout(callback) {
  if (typeof callback !== 'function') throw new TypeError('Expected a function');
}

// The native module answers only on macOS; elsewhere it is undefined.
function isISOKeyboard() {
  return undefined;
}


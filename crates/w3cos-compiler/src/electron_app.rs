//! `electron` / `@w3cos/electron` (M2): the compile-time half of the Electron
//! adapter.
//!
//! An Electron app hands its renderer side to the browser as files: the page
//! HTML (`loadFile('index.html')`), its `<script src>` files and the preload
//! named in `webPreferences.preload`. w3cos has no runtime loader or `eval`,
//! so the resolver turns `require('electron')` into the `w3cos-node`
//! Electron glue plus one generated CommonJS module, `electron_app.js`,
//! next to it. That module carries every page of the project (title, head and
//! body split at compile time, local stylesheets inlined) and a `load(file)`
//! switch whose literal `require()` calls put each renderer-side script into
//! the module graph, so preloads and page scripts are AOT-compiled with the
//! app and evaluated only when a window loads the page.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// Specifiers that resolve to the Electron glue. `electron` always does,
/// even with the `electron` npm package installed: that package is only the
/// prebuilt Chromium launcher, which an AOT-compiled app replaces.
pub const SPECIFIERS: &[&str] = &[
    "electron",
    "electron/main",
    "electron/renderer",
    "electron/common",
    "@w3cos/electron",
];

pub fn is_electron_specifier(specifier: &str) -> bool {
    SPECIFIERS.contains(&specifier)
}

/// Directories never scanned for pages or renderer scripts.
const SKIPPED_DIRS: &[&str] = &[
    "node_modules",
    "target",
    "bundle_run",
    // Code-OSS / Electron app trees: unit-test and build sources are not
    // renderer pages. Scanning them pulls test preloads (contextBridge) into
    // electron_app and OOMs / breaks codegen of the main graph.
    "test",
    "build",
    "src",
    "extensions",
    ".eslintplugin",
    "scripts",
    "out-build",
    ".git",
];
const MAX_DEPTH: usize = 8;

#[derive(Debug, Default, PartialEq)]
pub struct Page {
    pub title: String,
    pub head: String,
    pub body: String,
    /// Local `<script src>` files in document order, relative to the root.
    pub scripts: Vec<String>,
}

/// Source of the generated `electron_app.js` for the project at `root`.
pub fn app_module_source(root: &Path) -> String {
    app_module(root).0
}

/// [`app_module_source`] and the renderer-side script files it loads.
pub fn app_module(root: &Path) -> (String, Vec<PathBuf>) {
    let root = root.canonicalize().unwrap_or_else(|_| root.to_path_buf());
    let mut html = Vec::new();
    let mut js = Vec::new();
    collect_files(&root, 0, &mut html, &mut js);
    html.sort();
    js.sort();
    let mut modules = BTreeSet::new();
    let mut pages = Vec::new();
    for file in &html {
        let Ok(text) = std::fs::read_to_string(file) else {
            continue;
        };
        let page = parse_page(&text, file.parent().unwrap_or(&root), &root);
        modules.extend(page.scripts.iter().cloned());
        pages.push((relative(&root, file), page));
    }
    for file in &js {
        if is_preload_candidate(file) {
            modules.insert(relative(&root, file));
        }
    }
    let (name, version) = package_info(&root);
    let json = |value: &str| serde_json::to_string(value).expect("string to JSON");
    let mut out = String::from(
        "'use strict';\n// Generated by w3cos-compiler: this Electron app's pages and renderer-side\n// scripts (see crates/w3cos-compiler/src/electron_app.rs).\n",
    );
    out.push_str(&format!(
        "exports.root = {};\n",
        json(&root.to_string_lossy())
    ));
    out.push_str(&format!("exports.name = {};\n", json(&name)));
    out.push_str(&format!("exports.version = {};\n", json(&version)));
    out.push_str("exports.pages = {\n");
    for (file, page) in &pages {
        let scripts: Vec<String> = page.scripts.iter().map(|s| json(s)).collect();
        out.push_str(&format!(
            "  {}: {{ title: {}, head: {}, body: {}, scripts: [{}] }},\n",
            json(file),
            json(&page.title),
            json(&page.head),
            json(&page.body),
            scripts.join(", ")
        ));
    }
    out.push_str("};\nexports.modules = [");
    out.push_str(
        &modules
            .iter()
            .map(|m| json(m))
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str("];\nexports.load = function load(file) {\n  switch (file) {\n");
    for module in &modules {
        out.push_str(&format!(
            "    case {}: return require({});\n",
            json(module),
            json(&root.join(module).to_string_lossy())
        ));
    }
    out.push_str("    default: return undefined;\n  }\n};\n");
    let scripts = modules.iter().map(|module| root.join(module)).collect();
    (out, scripts)
}

fn collect_files(dir: &Path, depth: usize, html: &mut Vec<PathBuf>, js: &mut Vec<PathBuf>) {
    if depth > MAX_DEPTH {
        return;
    }
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().to_string();
        if name.starts_with('.') {
            continue;
        }
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() {
            if !SKIPPED_DIRS.contains(&name.as_str()) {
                collect_files(&path, depth + 1, html, js);
            }
        } else if name.ends_with(".html") || name.ends_with(".htm") {
            html.push(path);
        } else if name.ends_with(".js") || name.ends_with(".cjs") || name.ends_with(".mjs") {
            js.push(path);
        }
    }
}

/// A preload is named `preload*` or talks to the main process from the
/// renderer side (`contextBridge` / `ipcRenderer`) without creating windows.
fn is_preload_candidate(file: &Path) -> bool {
    // Never treat unit-test trees as app preloads (see SKIPPED_DIRS).
    if file.components().any(|c| c.as_os_str() == "test") {
        return false;
    }
    let stem = file
        .file_name()
        .map(|n| n.to_string_lossy().to_ascii_lowercase())
        .unwrap_or_default();
    if stem.contains(".test.") {
        return false;
    }
    if stem.starts_with("preload") {
        return true;
    }
    let Ok(text) = std::fs::read_to_string(file) else {
        return false;
    };
    (text.contains("contextBridge") || text.contains("ipcRenderer"))
        && !text.contains("BrowserWindow")
}

fn package_info(root: &Path) -> (String, String) {
    let manifest = std::fs::read_to_string(root.join("package.json"))
        .ok()
        .and_then(|text| serde_json::from_str::<serde_json::Value>(&text).ok());
    let field = |key: &str| {
        manifest
            .as_ref()
            .and_then(|m| m.get(key))
            .and_then(|v| v.as_str())
            .map(str::to_string)
    };
    (
        field("productName")
            .or_else(|| field("name"))
            .unwrap_or_default(),
        field("version").unwrap_or_default(),
    )
}

fn relative(root: &Path, file: &Path) -> String {
    file.strip_prefix(root)
        .unwrap_or(file)
        .to_string_lossy()
        .replace('\\', "/")
}

/// Split one page into title, head and body. Scripts are removed from the
/// markup (they run as compiled modules); local stylesheets become `<style>`.
pub fn parse_page(text: &str, dir: &Path, root: &Path) -> Page {
    let lower = text.to_ascii_lowercase();
    let head_range = element_inner(&lower, "head", 0);
    let body_range = element_inner(&lower, "body", head_range.map_or(0, |(_, end)| end));
    let head_src = head_range.map_or("", |(start, end)| &text[start..end]);
    let body_src = match body_range {
        Some((start, end)) => &text[start..end],
        None => {
            // No <body>: everything after </head> (or the whole document).
            let start = head_range
                .and_then(|(_, end)| lower[end..].find('>').map(|i| end + i + 1))
                .unwrap_or(0);
            &text[start..]
        }
    };
    let mut page = Page::default();
    let head = take_scripts(head_src, dir, root, &mut page.scripts);
    page.body = take_scripts(body_src, dir, root, &mut page.scripts);
    let (head, title) = take_title(&head);
    page.title = title;
    page.head = inline_stylesheets(&head, dir).trim().to_string();
    page.body = page.body.trim().to_string();
    page
}

/// Byte range of the content of the first `<name ...>...</name>` at or
/// after `from` (in the lowercased text).
fn element_inner(lower: &str, name: &str, from: usize) -> Option<(usize, usize)> {
    let open = find_tag(lower, name, from)?;
    let start = open + lower[open..].find('>')? + 1;
    let end = lower[start..]
        .find(&format!("</{name}"))
        .map_or(lower.len(), |i| start + i);
    Some((start, end))
}

/// Start of the next `<name` tag (followed by whitespace, `/` or `>`).
fn find_tag(lower: &str, name: &str, mut from: usize) -> Option<usize> {
    let needle = format!("<{name}");
    while let Some(i) = lower[from..].find(&needle) {
        let at = from + i;
        match lower.as_bytes().get(at + needle.len()) {
            Some(b) if b.is_ascii_whitespace() || *b == b'>' || *b == b'/' => return Some(at),
            None => return None,
            _ => from = at + needle.len(),
        }
    }
    None
}

fn take_scripts(src: &str, dir: &Path, root: &Path, scripts: &mut Vec<String>) -> String {
    let lower = src.to_ascii_lowercase();
    let mut out = String::new();
    let mut pos = 0;
    while let Some(open) = find_tag(&lower, "script", pos) {
        out.push_str(&src[pos..open]);
        let Some(tag_end) = lower[open..].find('>').map(|i| open + i + 1) else {
            pos = src.len();
            break;
        };
        let close = lower[tag_end..]
            .find("</script")
            .map(|i| tag_end + i)
            .unwrap_or(src.len());
        pos = lower[close..]
            .find('>')
            .map_or(src.len(), |i| close + i + 1);
        if let Some(src_attr) = attribute(&src[open..tag_end], "src")
            && let Some(file) = local_file(dir, &src_attr)
        {
            scripts.push(relative(root, &file));
        }
    }
    out.push_str(&src[pos.min(src.len())..]);
    out
}

fn take_title(head: &str) -> (String, String) {
    let lower = head.to_ascii_lowercase();
    let Some(open) = find_tag(&lower, "title", 0) else {
        return (head.to_string(), String::new());
    };
    let Some(start) = lower[open..].find('>').map(|i| open + i + 1) else {
        return (head.to_string(), String::new());
    };
    let close = lower[start..]
        .find("</title")
        .map_or(head.len(), |i| start + i);
    let end = lower[close..]
        .find('>')
        .map_or(head.len(), |i| close + i + 1);
    let title = decode_entities(&head[start..close])
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    (format!("{}{}", &head[..open], &head[end..]), title)
}

fn inline_stylesheets(head: &str, dir: &Path) -> String {
    let lower = head.to_ascii_lowercase();
    let mut out = String::new();
    let mut pos = 0;
    while let Some(open) = find_tag(&lower, "link", pos) {
        let Some(end) = lower[open..].find('>').map(|i| open + i + 1) else {
            break;
        };
        out.push_str(&head[pos..open]);
        let tag = &head[open..end];
        let is_stylesheet = attribute(tag, "rel").is_some_and(|rel| {
            rel.to_ascii_lowercase()
                .split_whitespace()
                .any(|r| r == "stylesheet")
        });
        let css = is_stylesheet
            .then(|| attribute(tag, "href"))
            .flatten()
            .and_then(|href| local_file(dir, &href))
            .and_then(|file| std::fs::read_to_string(file).ok());
        match css {
            Some(css) => {
                out.push_str("<style>");
                out.push_str(&css.replace("</style", "<\\/style"));
                out.push_str("</style>");
            }
            None => out.push_str(tag),
        }
        pos = end;
    }
    out.push_str(&head[pos..]);
    out
}

/// A same-app file reference (`./renderer.js`, `js/app.js`), not a URL.
fn local_file(dir: &Path, reference: &str) -> Option<PathBuf> {
    let reference = reference
        .split(['?', '#'])
        .next()
        .unwrap_or_default()
        .trim();
    if reference.is_empty()
        || reference.contains("://")
        || reference.starts_with("//")
        || reference.starts_with("data:")
    {
        return None;
    }
    let file = dir.join(reference.trim_start_matches('/'));
    let file = file.canonicalize().ok()?;
    file.is_file().then_some(file)
}

fn attribute(tag: &str, name: &str) -> Option<String> {
    let lower = tag.to_ascii_lowercase();
    let bytes = lower.as_bytes();
    let mut from = 0;
    while let Some(i) = lower[from..].find(name) {
        let at = from + i;
        from = at + name.len();
        if at == 0 || !bytes[at - 1].is_ascii_whitespace() {
            continue;
        }
        let rest = lower[from..].trim_start();
        let Some(rest) = rest.strip_prefix('=') else {
            continue;
        };
        let value_start = tag.len() - rest.trim_start().len();
        let value = &tag[value_start..];
        let parsed = match value.chars().next() {
            Some(quote @ ('"' | '\'')) => value[1..].split(quote).next().unwrap_or_default(),
            _ => value
                .split(|c: char| c.is_ascii_whitespace() || c == '>')
                .next()
                .unwrap_or_default(),
        };
        return Some(decode_entities(parsed));
    }
    None
}

fn decode_entities(text: &str) -> String {
    text.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&#39;", "'")
        .replace("&nbsp;", "\u{a0}")
        .replace("&amp;", "&")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pages_split_into_title_head_body_and_scripts() {
        let root = std::env::temp_dir().join("w3cos_electron_app_parse");
        let _ = std::fs::remove_dir_all(&root);
        std::fs::create_dir_all(root.join("js")).unwrap();
        std::fs::write(root.join("styles.css"), "h1 { color: red; }").unwrap();
        std::fs::write(root.join("js/app.js"), "").unwrap();
        std::fs::write(root.join("preload.js"), "").unwrap();
        std::fs::write(root.join("main.js"), "require('electron').BrowserWindow").unwrap();
        let html = r#"<!DOCTYPE html><html><head><meta charset="UTF-8"><title> A &amp; B </title>
<link href="./styles.css" rel="stylesheet"><link rel="icon" href="x.png"><script src="js/app.js"></script></head>
<body><h1>Hi</h1><script src="https://cdn/x.js"></script><SCRIPT src='./js/app.js?v=1' type="module"></SCRIPT></body></html>"#;
        std::fs::write(root.join("index.html"), html).unwrap();
        let root = root.canonicalize().unwrap();
        let page = parse_page(html, &root, &root);
        assert_eq!(page.title, "A & B");
        assert_eq!(
            page.head,
            "<meta charset=\"UTF-8\">\n<style>h1 { color: red; }</style><link rel=\"icon\" href=\"x.png\">"
        );
        assert_eq!(page.body, "<h1>Hi</h1>");
        assert_eq!(page.scripts, ["js/app.js", "js/app.js"]);
        let source = app_module_source(&root);
        assert!(
            source.contains("case \"preload.js\": return require("),
            "{source}"
        );
        assert!(source.contains("case \"js/app.js\""), "{source}");
        assert!(!source.contains("case \"main.js\""), "{source}");
        std::fs::remove_dir_all(root).ok();
    }
}
